  -X POST "$SITE/wp-json/wp/v2/posts" \
  -u "$USER:$PASS" \
  -H "Content-Type: application/json" \
  -d "{
    \"title\": \"$TITLE\",
    \"content\": $(echo "$CONTENT" | python3 -c 'import json,sys; print(json.dumps(sys.stdin.read()))'),
    \"status\": \"draft\"
  }")

