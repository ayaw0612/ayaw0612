<p>九条は神崎を見た。神崎が九条の目を確認した。左、右、正面。指を立てて動かした。視線が追えているか、焦点が合っているか。早瀬が横から腕に触れた。脈を取るような触れ方ではなかった。ただ、反応を確かめていた。</p>
<p>「問題ない」</p>
<p>九条が言った。</p>
<p>「私が判断する」</p>
<p>神崎は短く答えた。もう一度、九条の目を見た。数秒、黙って見た。それから頷いた。</p>
<p>「今夜は問題ない」</p>
<p>早瀬が手を離した。志水が膝の状態を確認し始めた。いつもの手順だった。いつもの触れ方だった。ただ、今日は少し時間をかけていた。九条はそれに気づいたが、何も言わなかった。</p>
<p>「インタビュー、何を話しましたか」</p>
<p>氷川が手元のメモを見ながら聞いた。確認ではなく、念のための照合だった。</p>
<p>九条は少し間を置いた。</p>
<p>「覚えていない」</p>
<p>部屋が静かになった。</p>
<p>「内容は問題なかったです」と氷川が言った。「チームへの感謝、次の全仏への意気込み。当たり障りなく話されていました」</p>
<p>そうか、と九条は思った。喋ったらしかった。当たり障りのないことを。何かを言ったという自覚はあったが、何を言ったかは残っていなかった。口が動いて、言葉が出て、カメラが捉えて、それで終わった。</p>
<p>志水がテーピングを外した。早瀬が左膝の可動域を確かめた。どこかが痛むわけではなかった。ただ重かった。</p>
<p>九条は天井を見た。</p>
<p>フローに入れなかった。</p>
<p>それだけが、引っかかっていた。インタビューが記憶にないことよりも、ヴォルに言われた言葉よりも、今夜の試合で最後まで深さに届かなかったことが、胸の中にあった。第二セットの途中から、潜ろうとして潜れなかった。原因は分からなかった。戦術的には処理した。勝った。だが、あの感覚のまま全仏に行くのは、違う。</p>
<p>「第二セット以降、フローに入れていなかった」</p>
<p>九条が言った。報告するような声だった。</p>
<p>蓮見が椅子に座ったまま九条を見た。何も言わなかった。</p>
<p>「原因の分析を明日やる」</p>
<p>九条が続けた。</p>
<p>蓮見はしばらく黙っていた。</p>
<p>「今夜は寝ろ」</p>
<p>それだけ言った。分析の否定ではなかった。今夜ではないということだった。</p>
<hr>
<p>チームが出ていった後、一人になった。</p>
<p>椅子に座ったまま、しばらく動かなかった。体が重かった。肺がまだ薄い空気を覚えていた。汗が冷えていた。</p>
<p>夜になっていた。</p>
<p>屋根の開いたコートから、空が見えていたことを思い出した。マドリードの空は街の光で少し白んでいた。星は見えなかった。</p>
<p>ヴォルの言葉が、どこかで残っていた。</p>
<p>⸺No one wins alone. Not forever.</p>
<p>九条はそれをもう一度、頭の中で聞いた。</p>
<p>人は一人で勝ち続けられるほど、強くない。</p>
<p>納得していなかった。</p>
<p>言葉の意味は分かる。実例も分かる。ヴォルにとってそれが真実なのも、否定する根拠はない。ただ、それが自分に当てはまるとは思わなかった。思えなかった。</p>
<p>弱くなれば負ける。負ければ、何も残らない。その等式は、九条の中でずっと揺らいでいない。</p>
<p>それなら俺は、人でなくていい。</p>
<p>本心から、そう思った。強がりではなかった。諦めでも自棄でもなかった。それが正しい結論だと、今も信じていた。</p>
<p>ただ⸺信じながら、ヴォルの言葉がまだそこにあった。処理を拒んでいるわけではない。反論も用意していない。ただ、消えなかった。引っかかりに形がなかった。</p>
<p>次は全仏だ、と九条は思った。</p>
<p>最もきつい山場。二週間。五セット制。赤土の上で、今年の全てが問われる。最も孤独の中で、最も長い忍耐が試される。それだけが、あった。</p>
<p>ヴォルの言葉の答えは、そこで出す。</p>
